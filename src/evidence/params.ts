/**
 * Parameters with no code site: assumptions other bindings depend on.
 *
 * These exist because a number can encode a decision without ever appearing as a
 * decision. `MASTERY_ALPHA = 0.4` is really "four correct answers should cross the
 * threshold" — and *that* is the pedagogical choice. Naming it makes it auditable
 * and puts it on the ratchet where it belongs.
 *
 * An implied parameter that nothing references is dead weight, so the test
 * requires each one to be an input to some other binding.
 */
