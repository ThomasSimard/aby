/**
 * The complete index of everything in aby that influences learning.
 *
 * This union is hand-written on purpose. Deriving it from the bindings registry
 * (`keyof typeof BINDINGS`) is circular — `Binding` references `ParamId` — and
 * TypeScript rejects it outright. Writing it by hand turns that limitation into
 * the stronger guarantee: `bindings/index.ts` is checked against
 * `{ [K in ParamId]: Binding<K> }`, so a declared parameter with no binding is a
 * *compile* error, not just an unbound number nobody noticed.
 *
 * Adding a line here is the deliberate act. It is meant to be slightly annoying.
 */

